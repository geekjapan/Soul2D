/// D `ngManifestEffectSlug` value for the tools whose effect is known by name.
pub fn effect_of(tool: &str) -> Option<&'static str> {
    if tool == "editor_quit" { return Some("application-lifecycle"); }
    [("-", READ_ONLY), ("project-reset", PROJECT_RESET), ("file-write", FILE_WRITE), ("import", IMPORT),
        ("clipboard-write", CLIPBOARD_WRITE)]
        .into_iter()
        .find(|(_, names)| names.contains(&tool))
        .map(|(slug, _)| slug)
}

/// The effect a tool's own definition states when no list names it: `document-edit` for a tool whose schema
/// takes `expectedRevision` (the host refuses the call when the document moved on, so the call edits it) or
/// whose operation reaches a document-replacing sink, `editor-state` for the remaining editor tools, and
/// `session-state` for a tool whose operation changes the session without reaching a sink.
fn effect_from_schema(tool: &str, schema: &Value) -> Option<&'static str> {
    if schema["properties"].get("expectedRevision").is_some() || DOCUMENT_EDIT.contains(&tool) {
        Some("document-edit")
    } else if EDITOR_TOOLS.contains(&tool) {
        Some("editor-state")
    } else if SESSION_STATE.contains(&tool) {
        Some("session-state")
    } else {
        None
    }
}

/// The manifest document: tools sorted by id, object keys sorted by serde_json, so the text is byte-stable.
pub fn build() -> Value {
    let mut commands: Vec<Value> = tool_list()
        .into_iter()
        .map(|tool| {
            let id = tool["name"].as_str().unwrap_or_default().to_owned();
            let mut entry = json!({
                "id": id,
                "description": tool["description"],
                "inputSchema": tool["inputSchema"],
                "scope": ["global"],
                "mcpExposed": true,
                "headless_ok": !EDITOR_TOOLS.contains(&id.as_str()),
            });
            if let Some(effect) = effect_of(&id).or_else(|| effect_from_schema(&id, &tool["inputSchema"])) {
                entry["effect"] = json!(effect);
            }
            if let Some((_, entries)) = GUI_ENTRIES.iter().find(|(tool, _)| *tool == id) {
                entry["guiEntry"] = json!(entries);
            }
            entry
        })
        .collect();
    commands.sort_by(|a, b| a["id"].as_str().cmp(&b["id"].as_str()));
    json!({"commands": commands, "generator": "soul2d-core --export-command-manifest"})
}

/// Pretty JSON with a trailing newline, the exact bytes `write` stores.
pub fn render() -> Result<String, String> {
    let mut text = serde_json::to_string_pretty(&build()).map_err(|error| error.to_string())?;
    text.push('\n');
    Ok(text)
}

pub fn write(path: &Path) -> Result<(), String> {
    let text = render()?;
    std::fs::write(path, text).map_err(|error| format!("could not write {}: {error}", path.display()))
}

/// `--check`: Ok when the file at `path` equals what `write` would produce.
pub fn check(path: &Path) -> Result<(), String> {
    let stored = std::fs::read_to_string(path).map_err(|error| format!("could not read {}: {error}", path.display()))?;
    if stored == render()? {
        Ok(())
    } else {
        Err(format!("{} is out of date; run soul2d-core --export-command-manifest {}", path.display(), path.display()))
    }
}
