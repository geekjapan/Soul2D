//! The command manifest of the Rust MCP tools, replacing D's `doc/commands.manifest.json` exporter
//! (`commands/manifest.d`, `tools/export-command-manifest.d`).
//!
//! D recorded its commands' registered metadata (scope, irreversible effect, GUI display). The Rust tools have
//! no such registry, so each entry states only what is true of every tool here (`scope`, `mcpExposed`), whether
//! the tool runs without a window (`headless_ok`, false for `mcp::EDITOR_TOOLS`), plus an `effect` slug for the
//! tools whose effect this module knows by name, from the tool's own schema or from the crate's call graph: a tool
//! that takes `expectedRevision` or whose operation reaches a document-replacing sink (`manifest_edit_ops.rs`,
//! generated by tools/gen-edit-ops.py) edits the document (`document-edit`), an editor tool with no file effect
//! sets window state (`editor-state`), and a tool whose operation reaches no sink but assigns a session field or
//! calls a `&mut self` method changes state the session holds without replacing the document, such as playback,
//! physics, attached runtimes, views, the split layout, the history limit or the internal clipboard
//! (`session-state`, also from `manifest_edit_ops.rs`). A tool none of these rules reaches carries no `effect` key rather than a guess.
//! `guiEntry` lists the Soul2D GUI entries that reach the tool, from `manifest_gui_entries.rs` (generated from the
//! inventory by tools/gen-gui-entries.py); a tool the inventory does not name has no `guiEntry` key.

