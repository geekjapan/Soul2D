#!/usr/bin/env python3
"""Regenerate tl/template.pot from the Rust sources (replaces the D-era genpot.sh).

The editor marks a translatable string by passing a literal to the lookup helpers `tr("...")`
(editor_ui.rs, editor_shell.rs) or `env.t("...")` (editor_windows.rs); there are no plural or
context forms. A call whose argument is `if c { "a" } else { "b" }` yields both strings. Strings that
reach `t(label)` through a table are listed in tl/genpot-extra.txt (see --dynamic).

    python3 tools/genpot.py            # write tl/template.pot
    python3 tools/genpot.py --check    # fail if tl/template.pot is stale
    python3 tools/genpot.py --dynamic  # list call sites whose argument is not a literal
    python3 tools/genpot.py --self-test

Standard library only. Output is sorted by file and line, so it is deterministic.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'rust/src'
POT = ROOT / 'tl/template.pot'
EXTRA = ROOT / 'tl/genpot-extra.txt'
HEADER = '''# Soul2D translation template.
# Generated by tools/genpot.py from rust/src/**/*.rs; do not edit by hand.
msgid ""
msgstr ""
"Project-Id-Version: soul2d\\n"
"Report-Msgid-Bugs-To: \\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
'''
SIMPLE_ESCAPES = {'n': '\n', 'r': '\r', 't': '\t', '\\': '\\', '0': '\0', "'": "'", '"': '"'}


def unescape(body):
    """Value of a Rust string literal body (without quotes)."""
    out, i = [], 0
    while i < len(body):
        c = body[i]
        if c != '\\':
            out.append(c)
            i += 1
            continue
        n = body[i + 1]
        if n in SIMPLE_ESCAPES:
            out.append(SIMPLE_ESCAPES[n])
            i += 2
        elif n == 'x':
            out.append(chr(int(body[i + 2:i + 4], 16)))
            i += 4
        elif n == 'u':
            end = body.index('}', i)
            out.append(chr(int(body[i + 3:end].replace('_', ''), 16)))
            i = end + 1
        elif n in '\r\n':  # line continuation: drop the newline and the next line's indentation
            i += 2
            while i < len(body) and body[i] in ' \t\r\n':
                i += 1
        else:
            raise ValueError(f'unknown escape \\{n}')
    return ''.join(out)


def tokenize(text):
    """Yield (kind, value, line) with kind in ident, str, punct. Comments and char literals are skipped."""
    i, line, n = 0, 1, len(text)
    while i < n:
        c = text[i]
        if c == '\n':
            line += 1
            i += 1
        elif c.isspace():
            i += 1
        elif text.startswith('//', i):
            i = text.find('\n', i)
            i = n if i < 0 else i
        elif text.startswith('/*', i):
            depth = 0
            while i < n:
                if text.startswith('/*', i):
                    depth += 1
                    i += 2
                elif text.startswith('*/', i):
                    depth -= 1
                    i += 2
                    if depth == 0:
                        break
                else:
                    line += text[i] == '\n'
                    i += 1
        else:
            m = re.compile(r'b?r(#*)"').match(text, i)
            if m:  # raw string
                end = text.find('"' + m.group(1), m.end())
                body = text[m.end():end]
                yield 'str', body, line
                line += body.count('\n')
                i = end + 1 + len(m.group(1))
            elif c == '"' or text.startswith('b"', i):
                start = i + (2 if c == 'b' else 1)
                j = start
                while text[j] != '"':
                    j += 2 if text[j] == '\\' else 1
                body = text[start:j]
                yield 'str', unescape(body), line
                line += body.count('\n')
                i = j + 1
            elif c == "'":  # char literal or lifetime
                m = re.compile(r"'(?:\\(?:x[0-9a-fA-F]{2}|u\{[0-9a-fA-F_]+\}|.)|[^\\'])'").match(text, i)
                if m:
                    i = m.end()
                else:
                    i += 1
            elif c.isalpha() or c == '_':
                m = re.compile(r'[A-Za-z_][A-Za-z0-9_]*').match(text, i)
                yield 'ident', m.group(), line
                i = m.end()
            elif c.isdigit():
                m = re.compile(r'[0-9][0-9A-Za-z_.]*').match(text, i)
                yield 'num', m.group(), line
                i = m.end()
            else:
                yield 'punct', c, line
                i += 1


def drop_test_items(tokens):
    """Remove every item that follows #[cfg(test)]."""
    out, i = [], 0
    cfg_test = ['#', '[', 'cfg', '(', 'test', ')', ']']
    while i < len(tokens):
        if [t[1] for t in tokens[i:i + 7]] == cfg_test:
            i += 7
            while tokens[i][1] == '#':  # further attributes on the same item
                depth = 0
                while True:
                    depth += tokens[i][1] == '['
                    depth -= tokens[i][1] == ']'
                    i += 1
                    if depth == 0:
                        break
            depth = 0
            while i < len(tokens):
                v = tokens[i][1] if tokens[i][0] == 'punct' else None
                depth += v == '{'
                depth -= v == '}'
                i += 1
                if (v == '}' and depth == 0) or (v == ';' and depth == 0):
                    break
        else:
            out.append(tokens[i])
            i += 1
    return out


def calls(tokens):
    """Yield (kind, value, line) for each lookup call: kind is 'msgid' or 'dynamic'."""
    for i, (_, v, line) in enumerate(tokens):
        prev = tokens[i - 1][1] if i else ''
        if tokens[i][0] != 'ident' or v not in ('tr', 't') or tokens[i + 1][1:2] != ('(',) or prev == 'fn':
            continue
        if v == 't' and prev != '.':
            continue
        depth, j, arg = 0, i + 1, []
        while True:
            depth += tokens[j][1] == '(' and tokens[j][0] == 'punct'
            depth -= tokens[j][1] == ')' and tokens[j][0] == 'punct'
            if depth == 0:
                break
            j += 1
            arg.append(tokens[j])
        arg = arg[:-1]
        if arg and arg[-1][1] == ',':
            arg = arg[:-1]
        if [t[1] for t in arg] == ['msgid']:  # the lookup wrappers themselves
            continue
        if len(arg) == 1 and arg[0][0] == 'str':
            yield 'msgid', arg[0][1], arg[0][2]
        elif arg and arg[0][1] == 'if':
            braced = [arg[k + 1] for k in range(len(arg) - 2)
                      if arg[k][1] == '{' and arg[k + 1][0] == 'str' and arg[k + 2][1] == '}']
            if braced:
                for tok in braced:
                    yield 'msgid', tok[1], tok[2]
            else:
                yield 'dynamic', '', line
        else:
            yield 'dynamic', ''.join(t[1] for t in arg), line


def po_quote(s):
    esc = s.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '\\t').replace('\r', '\\r')
    parts = esc.split('\n')
    lines = [p + '\\n' for p in parts[:-1]] + ([parts[-1]] if parts[-1] else [])
    if len(lines) == 1:
        return f'"{lines[0]}"'
    return '""\n' + '\n'.join(f'"{p}"' for p in lines)


def scan(files):
    """Return (msgids {msgid: [(file, line)]}, dynamic [(file, line, arg)], literals {value: (file, line)})."""
    msgids, dynamic, literals = {}, [], {}
    for path in files:
        rel = path.relative_to(ROOT).as_posix()
        tokens = drop_test_items(list(tokenize(path.read_text(encoding='utf-8'))))
        for kind, value, line in calls(tokens):
            if kind == 'msgid':
                msgids.setdefault(value, []).append((rel, line))
            else:
                dynamic.append((rel, line, value))
        for kind, value, line in tokens:  # genpot-extra.txt entries must match one of these
            if kind == 'str':
                literals.setdefault(value, (rel, line))
    return msgids, dynamic, literals


def render(msgids):
    entries = sorted(msgids.items(), key=lambda kv: (min(kv[1]), kv[0]))
    out = [HEADER]
    for msgid, locs in entries:
        refs = ' '.join(f'{f}:{n}' for f, n in sorted(set(locs)))
        out.append(f'#: {refs}\nmsgid {po_quote(msgid)}\nmsgstr ""\n')
    return '\n'.join(out)


def extras():
    if not EXTRA.exists():
        return []
    return [json.loads(l) for l in EXTRA.read_text(encoding='utf-8').splitlines() if l.strip() and not l.startswith('#')]


def generate():
    files = sorted(SRC.rglob('*.rs'), key=lambda p: p.relative_to(ROOT).as_posix())
    msgids, dynamic, literals = scan(files)
    stale = [e for e in extras() if e not in literals]
    if stale:
        sys.exit(f'tl/genpot-extra.txt names strings no source literal contains: {stale}')
    for e in extras():
        msgids.setdefault(e, []).append(literals[e])
    return render(msgids), dynamic


def self_test():
    src = r'''
fn tr(msgid: &str) -> String { x }
// ui.label(tr("in a comment"));
fn f() {
    ui.label(tr("Plain \"quoted\"\tTab"));
    ui.label(tr(
        "Multi-line \
         continued\n\nsecond",
    ));
    env.t(if dark { "Dark" } else { "Light" });
    env.t(label);
    let s = "tr(\"not a call\")";
    let c = '"'; let l: &'static str = env.t(r#"Raw "one""#);
    ui.label(tr("snow \u{2603} \x41"));
}
#[cfg(test)]
mod tests { fn g() { tr("only in tests"); } }
fn after() { tr("After tests"); }
'''
    tokens = drop_test_items(list(tokenize(src)))
    found = [(k, v) for k, v, _ in calls(tokens)]
    want = [('msgid', 'Plain "quoted"\tTab'), ('msgid', 'Multi-line continued\n\nsecond'), ('msgid', 'Dark'),
            ('msgid', 'Light'), ('dynamic', 'label'), ('msgid', 'Raw "one"'), ('msgid', 'snow \u2603 A'),
            ('msgid', 'After tests')]
    assert found == want, found
    assert po_quote('a\nb\n') == '""\n"a\\n"\n"b\\n"'
    assert po_quote('say "hi"') == '"say \\"hi\\""'
    print('PASS genpot self-test')


def main():
    arg = sys.argv[1] if len(sys.argv) > 1 else ''
    if arg == '--self-test':
        return self_test()
    pot, dynamic = generate()
    if arg == '--dynamic':
        for f, n, a in dynamic:
            print(f'{f}:{n}: t({a})')
    elif arg == '--check':
        if POT.read_text(encoding='utf-8') != pot:
            sys.exit('tl/template.pot is stale; run python3 tools/genpot.py')
        print('PASS tl/template.pot is current')
    elif arg == '':
        POT.write_text(pot, encoding='utf-8')
        print(f'wrote {POT.relative_to(ROOT)} with {pot.count("msgid ") - 1} messages; '
              f'{len(dynamic)} non-literal call sites (see --dynamic and tl/genpot-extra.txt)')
    else:
        sys.exit(__doc__)


if __name__ == '__main__':
    main()
