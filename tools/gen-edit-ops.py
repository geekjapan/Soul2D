#!/usr/bin/env python3
"""Generate rust/src/manifest_edit_ops.rs: the tools whose operation edits the document or the session (#99 section 7).

An operation edits the document when its dispatch arm in `Session::handle_inner` (`rust/src/lib.rs`) reaches,
through the methods and functions it calls, one of the sinks that replace the current model and move the
history or the revision: `commit_model`, `commit_model_keeping`, `rewrite_current`, `restore_history_index`.
The call graph holds the methods of the `impl Session` blocks and the free functions that take a session, with an
edge for each call made on the session (`self.x(`, `session.x(`) or with it (`x(self`); other calls are not
followed. The manifest states `document-edit` for the operations that reach a sink and the exporter leaves the
others without an effect key unless another rule names them. The graph cannot see a flag that keeps a function
from committing (`deformer.bezier_controls` reaches `commit_model` through `op_deformer_bezier(.., false)`), so
the exporter's by-name lists take precedence over this table.

An operation that reaches no sink changes session state when its arm assigns a field of the session (`self.x = ..`,
`self.x.push(..)`) or calls a method or function that takes the session as `&mut`; a `&self` method cannot change the
session (no field has interior mutability). The manifest states `session-state` for those: playback, physics,
attached Live2D runtimes, views, the split layout, the history limit, the internal clipboard and the depth-draw
workspace. An arm that reaches no sink and shows no mutation stays without a key, since the graph does not follow
calls made on other values.

The output is two sorted Rust tables of tool ids, `DOCUMENT_EDIT: &[&str]` and `SESSION_STATE: &[&str]`, with D
aliases resolved through `mcp_aliases.rs`; an alias is listed when every operation it sends to qualifies. Rerun
after changing operations, then re-export the manifest. `--check` exits 1 when the Rust file differs from what the
sources give; `--explain OP` prints the call path of one operation, or what makes it a session-state change.

usage: tools/gen-edit-ops.py [--check | --explain OP]
"""
import json
import re
import sys
from collections import deque
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "rust/src"
LIB = SRC / "lib.rs"
ALIASES = SRC / "mcp_aliases.rs"
MANIFEST = ROOT / "doc/commands.manifest.json"
OUT = SRC / "manifest_edit_ops.rs"
SINKS = {"commit_model", "commit_model_keeping", "rewrite_current", "restore_history_index"}
FN = re.compile(r"\bfn\s+([A-Za-z_][A-Za-z0-9_]*)\s*[<(]")
ARM_START = re.compile(r'^\s*(?:\|\s*)?"[a-z0-9_.]+"')
OP_LITERAL = re.compile(r'"([a-z0-9_.]+)"')
KEYWORDS = {"if", "match", "while", "for", "return", "Some", "Ok", "Err", "json", "format", "vec", "let", "fn", "move"}
HEADER = """//! Generated by tools/gen-edit-ops.py from the operations' call graph in rust/src. Do not edit.
//!
//! Tools whose operation reaches a document-replacing sink (`commit_model`, `commit_model_keeping`,
//! `rewrite_current`, `restore_history_index`); the manifest exporter states `document-edit` for them.

pub const DOCUMENT_EDIT: &[&str] = &[
"""
SESSION_HEADER = """
/// Tools whose operation reaches no sink but assigns a session field or calls a `&mut self` method; the manifest
/// exporter states `session-state` for those that no by-name list and no editor tool rule places first.
pub const SESSION_STATE: &[&str] = &[
"""
MUTATION = re.compile(
    r"\bself\.[a-z_][a-z0-9_.]*\s*(?:=[^=]|\+=|-=)"
    r"|\bself\.[a-z_][a-z0-9_.]*\.(?:push|insert|remove|clear|take|retain|extend|truncate|drain|pop|replace|swap|sort)\s*\("
)


def strip_comments(text):
    """Comments and the contents of string, raw-string and char literals replaced by spaces (length kept), so
    braces inside them do not count. A lifetime (`'a`) is not a char literal."""
    out = []
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i))
            i = j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out.append(" " * (j - i))
            i = j
        elif c == '"' or (c == "r" and re.match(r'r#*"', text[i:i + 8]) and not (i and (text[i - 1].isalnum() or text[i - 1] == "_"))):
            if c == '"':
                j = i + 1
                while j < n and text[j] != '"':
                    j += 2 if text[j] == "\\" else 1
                j = min(j + 1, n)
            else:
                hashes = len(text[i + 1:].split('"', 1)[0])
                close = '"' + "#" * hashes
                j = text.find(close, i + hashes + 2)
                j = n if j < 0 else j + len(close)
            out.append('"' + " " * (j - i - 2) + '"' if j - i >= 2 else text[i:j])
            i = j
        elif c == "'" and i + 2 < n and (text[i + 1] == "\\" or text[i + 2] == "'"):
            if text[i + 1] == "\\":
                j = text.find("'", i + 2)
                j = n if j < 0 else j + 1
            else:
                j = i + 3
            out.append("' '" + " " * (j - i - 3))
            i = j
        else:
            out.append(c)
            i += 1
    return "".join(out)


def brace_block(text, open_brace):
    """The text between the brace at `open_brace` and its match, exclusive."""
    depth = 0
    for i in range(open_brace, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[open_brace + 1:i]
    return text[open_brace + 1:]


def functions(text):
    """Every `fn` of `text` as (name, signature, body)."""
    for match in FN.finditer(text):
        open_brace = text.find("{", match.end())
        if open_brace < 0:
            continue
        signature = text[match.end():open_brace]
        depth = 0
        declaration = False
        for c in signature:  # a `;` outside parentheses and brackets ends a declaration without a body
            depth += c in "(["
            depth -= c in ")]"
            if c == ";" and depth == 0:
                declaration = True
                break
        if declaration:
            continue
        yield match.group(1), signature, brace_block(text, open_brace)


SESSION_IMPL = re.compile(r"^impl\s+(?:crate::)?Session\s*\{", re.M)
SESSION_PARAM = re.compile(r"\b([a-z_][a-z0-9_]*)\s*:\s*&(?:mut\s+)?(?:crate::)?Session\b")


def edges(body, receiver):
    """Function names `body` calls on the session held in `receiver` (`self` or a parameter name), or with it."""
    found = set(re.findall(rf"\b{receiver}\.([a-z_][A-Za-z0-9_]*)\s*\(", body))
    if receiver == "self":
        found |= set(re.findall(r"\bSelf::([a-z_][A-Za-z0-9_]*)\s*\(", body))
    found |= set(re.findall(rf"\b([a-z_][A-Za-z0-9_]*)\s*\(\s*(?:&mut\s+)?{receiver}\b", body))
    return found - KEYWORDS


def call_graph():
    """Session methods (from `impl Session` blocks) and free functions that take a session, by name, and the names
    among them that take the session as `&mut`."""
    graph = {}
    mutators = set()
    for path in sorted(SRC.glob("*.rs")):
        if path.name.startswith("editor_") or path.name == "window_shell.rs":
            continue  # the egui editor calls the session; it holds no operation
        text = strip_comments(path.read_text())
        for match in SESSION_IMPL.finditer(text):
            block = brace_block(text, text.index("{", match.start()))
            for name, signature, body in functions(block):
                graph.setdefault(name, set()).update(edges(body, "self"))
                if re.search(r"&\s*mut\s+self\b", signature.split(")")[0]):
                    mutators.add(name)
        for name, signature, body in functions(text):
            param = SESSION_PARAM.search(signature)
            if param:
                graph.setdefault(name, set()).update(edges(body, param.group(1)))
                if "&mut" in param.group(0):
                    mutators.add(name)
    for entry in ("handle_inner", "handle_request", "handle_prepared_request", "handle_mcp", "handle_mcp_guarded"):
        graph.pop(entry, None)  # re-entry through the dispatcher would make every operation reach every sink
    return graph, mutators


def dispatch_arms():
    """Operation name to (the function names its arm calls, the arm's text), from the `match op` of `handle_inner`."""
    text = re.sub(r"//[^\n]*", "", LIB.read_text())
    start = text.index("let result = match op {")
    body_start = text.index("{", start)
    body = brace_block(text, body_start)
    arms = {}
    current = None
    for line in body.splitlines():
        if ARM_START.match(line) and not line.lstrip().startswith("_ =>"):
            pattern, sep, rest = line.partition("=>")
            ops = OP_LITERAL.findall(pattern) if sep else OP_LITERAL.findall(line)
            if not line.lstrip().startswith("|"):
                current = []  # a continuation line (`| "op"`) extends the arm the previous line opened
            current.extend(ops)
            for op in current:
                arms.setdefault(op, (set(), ""))
            if sep:
                for op in current:
                    arms[op] = (arms[op][0] | edges(rest, "self"), arms[op][1] + rest + "\n")
            continue
        if current is not None:
            for op in current:
                arms[op] = (arms[op][0] | edges(line, "self"), arms[op][1] + line + "\n")
    return arms


def reaches_sink(graph, roots):
    """The call path from one of `roots` to a sink, or None."""
    queue = deque((root, [root]) for root in roots)
    seen = set(roots)
    while queue:
        name, path = queue.popleft()
        if name in SINKS:
            return path
        for callee in graph.get(name, ()):
            if callee not in seen:
                seen.add(callee)
                queue.append((callee, path + [callee]))
    return None


def mutation_of(calls, text, mutators):
    """What shows an arm changes the session: a `&mut` callee's name, `assignment`, or None."""
    named = sorted(calls & mutators)
    if named:
        return named[0]
    return "assignment" if MUTATION.search(text) else None


def classify_ops():
    """Operation to its sink path (`edit`) and, for the others, to what makes it a session-state change (`session`)."""
    graph, mutators = call_graph()
    edit, session = {}, {}
    for op, (calls, text) in dispatch_arms().items():
        path = reaches_sink(graph, calls)
        if path:
            edit[op] = path
        else:
            mutation = mutation_of(calls, text, mutators)
            if mutation:
                session[op] = mutation
    return edit, session


def edit_ops():
    return classify_ops()[0]


DOTTED = re.compile(r'"([a-z][a-z0-9_]*(?:\.[a-z0-9_]+)+|undo|redo)"')
ALIAS_ARM = re.compile(r'^        (?:"[A-Za-z0-9_]+"(?:\s*\|\s*"[A-Za-z0-9_]+")*|[a-z_]+ if .*|_) =>', re.M)
# Arms of `tool_request` that pick their tools with a predicate on the name; the tools each one covers.
PREDICATE_PREFIX = {
    "inspector_transform_component": "Inspector_Apply_",
    "inspector_node_property": "Inspector_Apply_",
    "inspector_physics_key": "Inspector_Apply_",
}


def arm_ops(body, tools, found):
    """Adds to `found` the dotted operations each arm of a `match name` body names, for the tools its pattern covers."""
    arms = list(ALIAS_ARM.finditer(body))
    for index, arm in enumerate(arms):
        header = arm.group(0)
        tail = body[arm.end():arms[index + 1].start() if index + 1 < len(arms) else len(body)]
        ops = set(DOTTED.findall(tail))
        names = set(re.findall(r'"([A-Za-z0-9_]+)"', header))
        for prefix in re.findall(r'starts_with\("([A-Za-z0-9_]+)"\)', header):
            names |= {tool for tool in tools if tool.startswith(prefix)}
        for predicate, prefix in PREDICATE_PREFIX.items():
            if predicate in header:
                names |= {tool for tool in tools if tool.startswith(prefix) and tool not in found}
        for name in names & tools:
            found.setdefault(name, set()).update(ops)


def alias_ops(tools):
    """Tool id to the operations `mcp::tool_request` (rust/src/mcp.rs) or `mcp_aliases::request` sends it to. A D
    alias of `SIBLING_TOOLS` takes its sibling's operations: the arm that serves several siblings picks the
    operation by name, which the text of the arm cannot show."""
    found = {}
    aliases = re.sub(r"//[^\n]*", "", ALIASES.read_text())
    for alias, op in re.findall(r'\("([A-Za-z0-9_]+)",\s*"([a-z0-9_.]+)"\)', aliases):
        if alias in tools:
            found.setdefault(alias, set()).add(op)
    arm_ops(brace_block(aliases, aliases.index("Some(match name {") + len("Some(match name ")), tools, found)
    text = re.sub(r"//[^\n]*", "", (SRC / "mcp.rs").read_text())
    start = text.index("fn tool_request(")
    arm_ops(brace_block(text, text.index("let op = match name {", start) + len("let op = match name ")), tools, found)
    table_start = text.index("const SIBLING_TOOLS")
    table = text[table_start:text.index("];", table_start)]
    by_tool = {op.replace(".", "_"): op for op in dispatch_arms()}
    for sibling, alias in re.findall(r'\("([a-z0-9_]+)",\s*"([A-Za-z0-9_]+)",\s*&\[', table):
        if alias in tools and sibling in by_tool:
            found[alias] = {by_tool[sibling]}
    return found


def tool_ids(ops):
    """Tool ids whose every operation reaches a sink: plain tools by name, aliases through `alias_ops`."""
    tools = {command["id"] for command in json.loads(MANIFEST.read_text())["commands"]}
    ids = {op.replace(".", "_") for op in ops if op.replace(".", "_") in tools}
    for alias, targets in alias_ops(tools).items():
        if targets and targets <= set(ops):
            ids.add(alias)
    return sorted(ids)


def table(ids):
    return "".join(f"    {json.dumps(tool)},\n" for tool in ids) + "];\n"


def render(edit_ids, session_ids):
    return HEADER + table(edit_ids) + SESSION_HEADER + table(session_ids)


def main(argv):
    if argv[:1] == ["--explain"] and len(argv) == 2:
        edit, session = classify_ops()
        if argv[1] in edit:
            print(" -> ".join(edit[argv[1]]))
        elif argv[1] in session:
            print(f"{argv[1]} reaches no sink; session state through {session[argv[1]]}")
        else:
            print(f"{argv[1]} reaches no sink and shows no mutation")
        return
    if argv not in ([], ["--check"]):
        sys.exit(f"unknown arguments {argv}")
    edit, session = classify_ops()
    edit_ids, session_ids = tool_ids(edit), tool_ids(session)
    text = render(edit_ids, session_ids)
    if argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date; run tools/gen-edit-ops.py")
        print(f"ok: {OUT.relative_to(ROOT)} matches the sources")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(edit)} operations / {len(edit_ids)} tools edit the document, "
          f"{len(session)} operations / {len(session_ids)} tools change session state")


if __name__ == "__main__":
    main(sys.argv[1:])
