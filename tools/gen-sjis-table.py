#!/usr/bin/env python3
"""Regenerate rust/src/mmd_motion/sjis_table.rs, the Shift-JIS (CP932) decoding table of the MMD name decoder.

    python3 tools/gen-sjis-table.py            # write rust/src/mmd_motion/sjis_table.rs
    python3 tools/gen-sjis-table.py --check    # fail if the committed file differs from what this would write

The table has one u16 per double-byte cell: 60 lead bytes (0x81..=0x9F, 0xE0..=0xFC) times 188 trail bytes
(0x40..=0x7E, 0x80..=0xFC), 0 for a pair that CP932 does not map. It is read from Python's built-in `cp932` codec, so
it holds JIS X 0208, NEC row 13, the NEC-selected IBM extensions, the IBM extensions and the user-defined area
(mapped to the private use area, as the codec does). Every mapped character is in the Basic Multilingual Plane.
The file also records the mapped count and an FNV-1a checksum of the table, which a Rust test recomputes through the
decoder.

Standard library only. The output is deterministic.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'rust/src/mmd_motion/sjis_table.rs'
LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
TRAILS = list(range(0x40, 0x7F)) + list(range(0x80, 0xFD))
PER_LINE = 12


def cell(lead, trail):
    """Code point of the pair in CP932, or 0 when the codec does not map it."""
    try:
        text = bytes([lead, trail]).decode('cp932')
    except UnicodeDecodeError:
        return 0
    assert len(text) == 1 and ord(text) <= 0xFFFF, (lead, trail, text)
    return ord(text)


def fnv1a(values):
    """32-bit FNV-1a over the values, one step per u16 (not per byte); the Rust test does the same."""
    h = 0x811C9DC5
    for value in values:
        h = ((h ^ value) * 0x01000193) & 0xFFFFFFFF
    return h


def generate():
    values = [cell(lead, trail) for lead in LEADS for trail in TRAILS]
    lines = [
        "// Generated by tools/gen-sjis-table.py from Python's cp932 codec. Do not edit by hand;",
        '// run `python3 tools/gen-sjis-table.py` to rewrite it and `--check` to verify it.',
        '',
        '/// Trail bytes per lead byte (0x40..=0x7E and 0x80..=0xFC).',
        f'pub(super) const TRAIL_COUNT: usize = {len(TRAILS)};',
        '',
        '/// Mapped double-byte pairs (cells that are not 0).',
        '#[cfg(test)]',
        f'pub(super) const MAPPED_COUNT: usize = {sum(1 for v in values if v)};',
        '',
        '/// FNV-1a over the table, one step per u16, for the test that reads it back through the decoder.',
        '#[cfg(test)]',
        f'pub(super) const CHECKSUM: u32 = 0x{fnv1a(values):08X};',
        '',
        '/// Row `lead_index * TRAIL_COUNT`, column `trail_index`; 0 means unmapped.',
        '#[rustfmt::skip]',
        f'pub(super) const TABLE: [u16; {len(values)}] = [',
    ]
    for start in range(0, len(values), PER_LINE):
        lines.append('    ' + ' '.join(f'0x{v:04X},' for v in values[start:start + PER_LINE]))
    lines.append('];')
    return '\n'.join(lines) + '\n'


def main():
    arg = sys.argv[1] if len(sys.argv) > 1 else ''
    text = generate()
    if arg == '--check':
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            sys.exit(f'{OUT.relative_to(ROOT)} is stale; run python3 tools/gen-sjis-table.py')
        print(f'PASS {OUT.relative_to(ROOT)} is current')
    elif arg == '':
        OUT.write_text(text, encoding='utf-8')
        print(f'wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)')
    else:
        sys.exit(__doc__)


if __name__ == '__main__':
    main()
