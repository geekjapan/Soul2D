#!/usr/bin/env python3
"""Generate rust/src/manifest_gui_entries.rs from the Soul2D rows of doc/gui-operation-inventory.md (#99 section 7).

The inventory is the record of which Soul2D GUI entry reaches which tool. This script turns its three Soul2D
tables (the incremental table at the top, "Soul2D editor menu bar" and "Soul2D editor panels") into one sorted
Rust table `GUI_ENTRIES: &[(&str, &[&str])]` of tool id to GUI entries, which the manifest exporter writes as
`guiEntry`. A tool the inventory does not name gets no `guiEntry` key. Rerun after editing the inventory, then
re-export the manifest. `--check` exits 1 when the Rust file differs from what the inventory gives.

usage: tools/gen-gui-entries.py [--check]
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "doc/gui-operation-inventory.md"
MANIFEST = ROOT / "doc/commands.manifest.json"
OUT = ROOT / "rust/src/manifest_gui_entries.rs"
SOUL2D_SECTIONS = ("Soul2D editor menu bar", "Soul2D editor panels")
TOOL = re.compile(r"[A-Za-z0-9_]+")
HEADER = """//! Generated by tools/gen-gui-entries.py from the Soul2D rows of doc/gui-operation-inventory.md. Do not edit.
//!
//! Tool id to the Soul2D GUI entries that reach it, sorted by id; the manifest exporter writes them as `guiEntry`.

pub const GUI_ENTRIES: &[(&str, &[&str])] = &[
"""


def rows(lines):
    return [line for line in lines if line.startswith("| ") and not line.startswith("|---")][1:]


def cells(line):
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def section(lines, title):
    start = next(i for i, line in enumerate(lines) if line.startswith("## " + title))
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
    return lines[start:end]


def entries():
    tools = {command["id"] for command in json.loads(MANIFEST.read_text())["commands"]}
    lines = INVENTORY.read_text().splitlines()
    first_heading = next(i for i, line in enumerate(lines) if line.startswith("## "))
    found = {}
    # Incremental table: | Operation | Source GUI entry | Agent action | ...; tools are backticked calls.
    for line in rows(lines[:first_heading]):
        parts = cells(line)
        if len(parts) < 3:
            continue
        for tool in re.findall(r"`([A-Za-z0-9_]+)", parts[2]):
            if tool in tools:
                found.setdefault(tool, set()).add(parts[1])
    # Menu bar and panels: | Menu entry or Panel | Dispatch or Controls | Session operation / tool | Status |
    for title in SOUL2D_SECTIONS:
        for line in rows(section(lines, title)):
            parts = cells(line)
            if len(parts) < 4:
                continue
            for tool in TOOL.findall(parts[2]):
                if tool in tools:
                    found.setdefault(tool, set()).add(parts[0])
    return {tool: sorted(names) for tool, names in sorted(found.items())}


def render(table):
    def lit(text):
        return json.dumps(text, ensure_ascii=False)

    body = "".join(
        f"    ({lit(tool)}, &[\n" + "".join(f"        {lit(name)},\n" for name in names) + "    ]),\n"
        for tool, names in table.items()
    )
    return HEADER + body + "];\n"


def main(argv):
    check = argv == ["--check"]
    if argv and not check:
        sys.exit(f"unknown arguments {argv}")
    table = entries()
    text = render(table)
    if check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date; run tools/gen-gui-entries.py")
        print(f"ok: {OUT.relative_to(ROOT)} matches the inventory")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(table)} tools with a GUI entry")


if __name__ == "__main__":
    main(sys.argv[1:])
