#!/usr/bin/env python3
"""Write doc/licenses/rust-dependencies.tsv and rust-dependencies-licenses.txt from offline cargo metadata.

Lists every non-workspace crate in the locked graph (all features) for the Linux, macOS and Windows
release targets, with the platforms that resolve it. The second file holds the licence, copying and notice
files those crates ship, each text once with the crates that carry it. Needs only the crates already in the
Cargo cache.
"""
import hashlib
import json
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parents[1]
targets = {'linux': 'x86_64-unknown-linux-gnu', 'macos': 'aarch64-apple-darwin', 'windows': 'x86_64-pc-windows-msvc'}
crates = {}
manifests = {}
for platform, triple in targets.items():
    out = subprocess.run(
        ['cargo', 'metadata', '--offline', '--locked', '--format-version', '1', '--all-features',
         '--filter-platform', triple, '--manifest-path', str(root / 'rust/Cargo.toml')],
        check=True, capture_output=True, text=True).stdout
    for p in json.loads(out)['packages']:
        if p['source'] is None:  # workspace member
            continue
        entry = crates.setdefault((p['name'], p['version']),
                                  (p['license'] or p['license_file'] or 'NONE', p['repository'] or '', set()))
        entry[2].add(platform)
        manifests[(p['name'], p['version'])] = Path(p['manifest_path']).parent
lines = ['package\tversion\tdeclared_license\trepository\tplatforms']
for (name, version), (lic, repo, platforms) in sorted(crates.items()):
    lines.append(f"{name}\t{version}\t{lic}\t{repo}\t{','.join(sorted(platforms))}")
(root / 'doc/licenses/rust-dependencies.tsv').write_text('\n'.join(lines) + '\n')
print(f'wrote {len(crates)} crates to doc/licenses/rust-dependencies.tsv')

texts, missing = {}, []
for (name, version), directory in sorted(manifests.items()):
    files = sorted(f for f in directory.iterdir() if f.is_file()
                   and f.name.upper().startswith(('LICENSE', 'LICENCE', 'COPYING', 'NOTICE', 'UNLICENSE')))
    if not files:
        missing.append(f'{name} {version}')
    for f in files:
        text = f.read_text(errors='replace').replace('\r\n', '\n').strip()
        texts.setdefault(hashlib.sha256(text.encode()).hexdigest(), (text, []))[1].append(f'{name} {version} ({f.name})')
blocks = ['Licence, copying and notice files shipped by the Rust crates compiled into Soul2D.\n'
          'Generated by tools/gen-third-party-crates.py; identical texts appear once.\n']
if missing:
    blocks.append('Crates that ship no licence file (see rust-dependencies.tsv for the declared licence):\n'
                  + '\n'.join(missing) + '\n')
for text, users in sorted(texts.values(), key=lambda item: item[1]):
    blocks.append('=' * 100 + '\n' + '\n'.join(users) + '\n' + '-' * 100 + '\n' + text + '\n')
(root / 'doc/licenses/rust-dependencies-licenses.txt').write_text('\n'.join(blocks))
print(f'wrote {len(texts)} distinct texts for {len(manifests) - len(missing)} crates; {len(missing)} ship none')
